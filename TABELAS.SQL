CREATE TABLE Usuarios (
                          id_usuario      INTEGER GENERATED BY DEFAULT AS IDENTITY,
                          nome            VARCHAR2(100) NOT NULL,
                          email           VARCHAR2(100) NOT NULL,
                          senha           VARCHAR2(50) NOT NULL,
                          data_nascimento DATE NOT NULL,
                          pontos          INTEGER DEFAULT 0 NOT NULL,

                          CONSTRAINT Usuarios_PK PRIMARY KEY (id_usuario),
                          CONSTRAINT Usuarios_Email_UK UNIQUE (email),
                          CONSTRAINT Usuarios_Pontos_CK CHECK (pontos >= 0)
);


CREATE TABLE Itens (
                       id_item      INTEGER GENERATED BY DEFAULT AS IDENTITY,
                       nome         VARCHAR2(80) NOT NULL,
                       modelo_item  VARCHAR2(30) NOT NULL,
                       valor_pontos INTEGER,
                       tipo         VARCHAR2(10) NOT NULL,

                       CONSTRAINT Itens_PK PRIMARY KEY (id_item),

                       CONSTRAINT Itens_Tipo_CK
                           CHECK (tipo IN ('NORMAL', 'EXCLUSIVO')),

                       CONSTRAINT Itens_Modelo_Item_CK
                           CHECK (
                               modelo_item IN (
                                               'CABELO',
                                               'ROUPA DE CIMA INTERNA',
                                               'ROUPA DE CIMA EXTERNA',
                                               'ROUPA DE BAIXO',
                                               'CALCADO',
                                               'ACESSORIO'
                                   )
                               ),

                       CONSTRAINT Itens_Valor_Pontos_CK
                           CHECK (valor_pontos >= 0)
);


CREATE TABLE Parcerias (
                           id_parceria  INTEGER GENERATED BY DEFAULT AS IDENTITY,
                           tipo         VARCHAR2(10) NOT NULL,
                           nome         VARCHAR2(100) NOT NULL,
                           status       VARCHAR2(7) DEFAULT 'ATIVA' NOT NULL,
                           custo_mensal NUMBER(13,2) NOT NULL,
                           data_inicio  DATE DEFAULT SYSDATE NOT NULL,
                           data_fim     DATE,

                           CONSTRAINT Parcerias_PK PRIMARY KEY (id_parceria),

                           CONSTRAINT Parcerias_Tipo_CK
                               CHECK (tipo IN ('INFLUENCER', 'MARCA')),

                           CONSTRAINT Parcerias_Status_CK
                               CHECK (status IN ('ATIVA', 'INATIVA')),

                           CONSTRAINT Parcerias_Custo_Mensal_CK
                               CHECK (custo_mensal >= 0)
);


CREATE TABLE Missoes (
                         id_missao INTEGER GENERATED BY DEFAULT AS IDENTITY,
                         titulo    VARCHAR2(100) NOT NULL,
                         descricao VARCHAR2(150) NOT NULL,
                         pontos    INTEGER NOT NULL,
                         tipo      VARCHAR2(10) NOT NULL,

                         CONSTRAINT Missoes_PK PRIMARY KEY (id_missao),

                         CONSTRAINT Missoes_Tipo_CK
                             CHECK (tipo IN ('DIARIA', 'SEMANAL', 'ESPECIAL')),

                         CONSTRAINT Missoes_Pontos_CK
                             CHECK (pontos >= 0)
);


CREATE TABLE Avatares (
                          id_avatar         INTEGER GENERATED BY DEFAULT AS IDENTITY,
                          nome              VARCHAR2(50) NOT NULL,
                          id_cabelo         INTEGER NOT NULL,
                          id_roupa_cima_int INTEGER NOT NULL,
                          id_roupa_cima_ext INTEGER NOT NULL,
                          id_roupa_baixo    INTEGER NOT NULL,
                          id_calcado        INTEGER NOT NULL,
                          id_acessorio      INTEGER NOT NULL,
                          id_usuario        INTEGER NOT NULL,

                          CONSTRAINT Avatares_PK PRIMARY KEY (id_avatar),

                          CONSTRAINT Avatares_Id_Usuario_UK
                              UNIQUE (id_usuario),

                          CONSTRAINT Avatares_Usuarios_FK
                              FOREIGN KEY (id_usuario)
                                  REFERENCES Usuarios (id_usuario)
);


CREATE TABLE Codigos (
                         id_codigo      INTEGER GENERATED BY DEFAULT AS IDENTITY,
                         codigo_resgate VARCHAR2(20) NOT NULL,
                         status         VARCHAR2(10) DEFAULT 'DISPONIVEL' NOT NULL,
                         data_validade  DATE NOT NULL,
                         data_resgate   DATE,
                         id_item        INTEGER NOT NULL,
                         id_parceria    INTEGER NOT NULL,

                         CONSTRAINT Codigos_PK PRIMARY KEY (id_codigo),

                         CONSTRAINT Codigo_Resgate_UK
                             UNIQUE (codigo_resgate),

                         CONSTRAINT Codigo_Status_CK
                             CHECK (status IN ('DISPONIVEL', 'RESGATADO')),

                         CONSTRAINT Codigos_Itens_FK
                             FOREIGN KEY (id_item)
                                 REFERENCES Itens (id_item),

                         CONSTRAINT Codigos_Parcerias_FK
                             FOREIGN KEY (id_parceria)
                                 REFERENCES Parcerias (id_parceria)
);


CREATE TABLE Inventario (
                            id_inventario  INTEGER GENERATED BY DEFAULT AS IDENTITY,
                            id_usuario     INTEGER NOT NULL,
                            id_item        INTEGER NOT NULL,
                            origem         VARCHAR2(10) NOT NULL,
                            data_aquisicao DATE DEFAULT SYSDATE NOT NULL,

                            CONSTRAINT Inventario_PK PRIMARY KEY (id_inventario),

                            CONSTRAINT Inventario_Origem_CK
                                CHECK (origem IN ('COMPRA', 'RESGATE')),

                            CONSTRAINT Inventario_Usuarios_FK
                                FOREIGN KEY (id_usuario)
                                    REFERENCES Usuarios (id_usuario),

                            CONSTRAINT Inventario_Itens_FK
                                FOREIGN KEY (id_item)
                                    REFERENCES Itens (id_item)
);


CREATE TABLE Logs (
                      id_log        INTEGER GENERATED BY DEFAULT AS IDENTITY,
                      assunto       VARCHAR2(30) NOT NULL,
                      descricao     VARCHAR2(150) NOT NULL,
                      data_registro DATE DEFAULT SYSDATE NOT NULL,
                      id_usuario    INTEGER NOT NULL,
                      status        VARCHAR2(10) NOT NULL,

                      CONSTRAINT Logs_PK PRIMARY KEY (id_log),

                      CONSTRAINT Logs_Status_CK
                          CHECK (status IN ('SUCESSO', 'ERRO')),

                      CONSTRAINT Logs_Usuarios_FK
                          FOREIGN KEY (id_usuario)
                              REFERENCES Usuarios (id_usuario)
);


CREATE TABLE Missoes_Usuario (
                                 id_missao_usuario INTEGER GENERATED BY DEFAULT AS IDENTITY,
                                 status            VARCHAR2(10) DEFAULT 'DISPONIVEL' NOT NULL,
                                 data_realizacao   DATE,
                                 id_usuario        INTEGER NOT NULL,
                                 id_missao         INTEGER NOT NULL,
                                 data_inicio       DATE DEFAULT SYSDATE NOT NULL,
                                 data_fim          DATE NOT NULL,

                                 CONSTRAINT Missoes_Usuario_PK
                                     PRIMARY KEY (id_missao_usuario),

                                 CONSTRAINT Missoes_Usuario_Status_CK
                                     CHECK (status IN ('DISPONIVEL', 'EXPIRADA')),

                                 CONSTRAINT Missoes_Usuario_Usuarios_FK
                                     FOREIGN KEY (id_usuario)
                                         REFERENCES Usuarios (id_usuario),

                                 CONSTRAINT Missoes_Usuario_Missoes_FK
                                     FOREIGN KEY (id_missao)
                                         REFERENCES Missoes (id_missao)
);